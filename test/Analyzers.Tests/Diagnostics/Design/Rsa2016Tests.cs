using System.Linq;
using System.Threading.Tasks;
using FluentAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Rocket.Surgery.Airframe.Analyzers.Diagnostics.Design;

namespace Rocket.Surgery.Airframe.Analyzers.Tests.Diagnostics.Design;

public class Rsa2016Tests
{
    [Theory]
    [ClassData(typeof(RedundantCases))]
    public async Task GivenSameNameAlias_WhenRemovalPreservesBinding_ThenReportsTheDirective(string source)
    {
        // Given
        var compilation = CreateCompilation(source);
        compilation.GetDiagnostics().Where(item => item.Severity == DiagnosticSeverity.Error).Should().BeEmpty();

        // When
        var diagnostics = await compilation.WithAnalyzers([new Rsa2016()]).GetAnalyzerDiagnosticsAsync();

        // Then
        var diagnostic = diagnostics.Should().ContainSingle().Subject;
        diagnostic.Id.Should().Be("RSA2016");
        diagnostic.Severity.Should().Be(DiagnosticSeverity.Warning);
        source.Substring(diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length).Should().StartWith("using ").And.EndWith(";");
    }

    [Theory]
    [ClassData(typeof(NecessaryCases))]
    public async Task GivenIntentionalOrUnprovableAlias_WhenAnalyzed_ThenKeepsTheAlias(string source)
    {
        // Given
        var compilation = CreateCompilation(source);
        compilation.GetDiagnostics().Where(item => item.Severity == DiagnosticSeverity.Error).Should().BeEmpty();

        // When
        var diagnostics = await compilation.WithAnalyzers([new Rsa2016()]).GetAnalyzerDiagnosticsAsync();

        // Then
        diagnostics.Should().BeEmpty();
    }

    [Theory]
    [InlineData("using N; using Item = Missing.Item; class Consumer { Item Value; } namespace N { public class Item { } }")]
    [InlineData("using N; using Item = ; class Consumer { Item Value; } namespace N { public class Item { } }")]
    [InlineData("#nullable enable\nusing N; using Item = N.Item?; class Consumer { Item Value; } namespace N { public class Item { } }")]
    public async Task GivenIncompleteOrUnsupportedAlias_WhenAnalyzed_ThenNoDiagnosticOrAnalyzerFailure(string source)
    {
        // Given
        var compilation = CreateCompilation(source);

        // When
        var diagnostics = await compilation.WithAnalyzers([new Rsa2016()]).GetAnalyzerDiagnosticsAsync();

        // Then
        diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task GivenOtherDocumentsWithTheSameName_WhenAnalyzed_ThenLocalAliasDoesNotAffectThem()
    {
        // Given
        var compilation = CreateCompilation("using N; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }")
           .AddSyntaxTrees(CSharpSyntaxTree.ParseText("namespace Other { class Item { } class Consumer { Item Value = new Item(); } }", new CSharpParseOptions(LanguageVersion.Preview)));

        // When
        var diagnostics = await compilation.WithAnalyzers([new Rsa2016()]).GetAnalyzerDiagnosticsAsync();

        // Then
        diagnostics.Should().ContainSingle().Which.Id.Should().Be("RSA2016");
    }

    [Fact]
    public async Task GivenGeneratedSource_WhenAnalyzed_ThenNoCleanupIsReported()
    {
        // Given
        var compilation = CreateCompilation("// <auto-generated/>\nusing N; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }");

        // When
        var diagnostics = await compilation.WithAnalyzers([new Rsa2016()]).GetAnalyzerDiagnosticsAsync();

        // Then
        diagnostics.Should().BeEmpty();
    }

    private static CSharpCompilation CreateCompilation(string source) => CSharpCompilation.Create(
        "Aliases",
        [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview, documentationMode: DocumentationMode.Diagnose))],
        [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

    public sealed class RedundantCases : TheoryData<string>
    {
        public RedundantCases()
        {
            Add("using N; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }");
            Add("using System; namespace C; using String = System.String; class Consumer { String Value = String.Empty; }");
            Add("namespace C { using N; using Item = N.Item; class Consumer { Item Value = new Item(); } } namespace N { public class Item { } }");
            Add("using static N.Outer; using Item = N.Outer.Item; class Consumer { Item Value = new Item(); } namespace N { public class Outer { public class Item { } } }");
            Add("using static N.Outer<string>; using Item = N.Outer<string>.Item; class Consumer { Item Value = new Item(); } namespace N { public class Outer<T> { public class Item { } } }");
            Add("using N; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } } namespace Inner { using Item = Other.Item; class Consumer { Item Value = new Item(); } } namespace Other { public class Item { } }");
            Add("using System; using String = System.String; class Consumer { String Value = String.Empty; }");
            Add("global using N; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }");
            Add("using N; using @Item = global::N.Item; class Consumer { @Item Value = new @Item(); } namespace N { public class Item { } }");
            Add("using N; using Item = N.Item; class Consumer { string Name => nameof(Item); } namespace N { public class Item { } }");
            Add("using N; using ItemAttribute = N.ItemAttribute; [Item] class Consumer { } namespace N { public class ItemAttribute : System.Attribute { } }");
            Add("using N; using Item = N.Item; /// <summary><see cref=\"Item\"/></summary>\nclass Consumer { } namespace N { public class Item { } }");
        }
    }

    public sealed class NecessaryCases : TheoryData<string>
    {
        public NecessaryCases()
        {
            Add("using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }");
            Add("using N; using Other; using Item = N.Item; class Consumer { Item Value = new Item(); } namespace N { public class Item { } } namespace Other { public class Item { } }");
            Add("using N; using Alias = N.Item; class Consumer { Alias Value = new Alias(); } namespace N { public class Item { } }");
            Add("using Item = N.Item; namespace N { public class Item { } class Consumer { Item Value = new Item(); } }");
            Add("using Alias = N; class Consumer { Alias.Item Value = new Alias.Item(); } namespace N { public class Item { } }");
            Add("global using Item = N.Item; using N; class Consumer { Item Value = new Item(); } namespace N { public class Item { } }");
            Add("using N; using Item = N.Item; class Consumer { } namespace N { public class Item { } }");
            Add("using N; using Item = N.Item<int>; class Consumer { Item Value = new Item(); } namespace N { public class Item<T> { } }");
            Add("#nullable enable\nusing static N.Outer<string?>; using Item = N.Outer<string>.Item; class Consumer { Item Value = new Item(); } namespace N { public class Outer<T> { public class Item { } } }");
            Add("using N; using Item = N.Item; namespace C { class Item { } class Consumer { Item Value = new Item(); } } namespace N { public class Item { } }");
            Add("using N; using Item = N.Item; class Consumer<Item> { Item Value; } namespace N { public class Item { } }");
            Add("using N; using ItemAttribute = N.ItemAttribute; namespace C { public class ItemAttribute : System.Attribute { } [Item] class Consumer { } } namespace N { public class ItemAttribute : System.Attribute { } }");
            Add("global using Other; using N; using Item = N.Item; /// <summary><see cref=\"Item\"/></summary>\nclass Consumer { } namespace N { public class Item { } } namespace Other { public class Item { } }");
        }
    }
}
